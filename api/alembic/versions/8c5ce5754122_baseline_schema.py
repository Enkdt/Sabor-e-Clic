def _criar_triggers_agendamento():
    """Triggers SQLite que impedem sobreposição de bancada; só agendamentos ACEITOS ocupam o horário.
    Alembic/SQLAlchemy não têm API para TRIGGER, então usa-se op.execute (inevitável)."""
    if op.get_bind().dialect.name != "sqlite":
        return
    condicao = (
        "existing.id_bancada = NEW.id_bancada "
        "AND existing.status = 'aceito' "
        "AND julianday(NEW.horario_agendado) < julianday(existing.horario_agendado) + (existing.tempo_agendado / 1440.0) "
        "AND julianday(existing.horario_agendado) < julianday(NEW.horario_agendado) + (NEW.tempo_agendado / 1440.0)"
    )
    abortar = "SELECT RAISE(ABORT, 'A bancada já tem um agendamento nesse intervalo.');"
    op.execute(f"""
        CREATE TRIGGER prevent_agendamento_overlap_insert
        BEFORE INSERT ON agendamento
        WHEN NEW.status = 'aceito' AND EXISTS (SELECT 1 FROM agendamento existing WHERE {condicao})
        BEGIN {abortar} END
    """)
    op.execute(f"""
        CREATE TRIGGER prevent_agendamento_overlap_update
        BEFORE UPDATE OF id_bancada, horario_agendado, tempo_agendado, status ON agendamento
        WHEN NEW.status = 'aceito' AND EXISTS (SELECT 1 FROM agendamento existing WHERE existing.id != NEW.id AND {condicao})
        BEGIN {abortar} END
    """)


